    def fetch_holidays(self, year, country="IN"):
        """Fetch holidays with caching and timeout safety"""
        if year in HOLIDAY_CACHE:
            return HOLIDAY_CACHE[year]

        url = f"https://date.nager.at/api/v3/PublicHolidays/{year}/{country}"
        try:
            # Short timeout to prevent UI freezing
            response = requests.get(url, timeout=5)
            if response.status_code == 200:
                data = response.json()
                holidays = {
                    datetime.strptime(h["date"], "%Y-%m-%d").date()
                    for h in data
                }
                HOLIDAY_CACHE[year] = holidays
                return holidays
        except Exception as e:
            print(f"Warning: Could not fetch holidays for {year}: {e}")
            
        # Fallback to empty set if fetch fails
        HOLIDAY_CACHE[year] = set()
        return set()

    def calculate_working_days(self, month, year):
        """
        OPTIMIZATION: Memoized working days calculation.
        """
        cache_key = (month, year)
        if cache_key in self.working_days_cache:
            return self.working_days_cache[cache_key]

        holidays = self.fetch_holidays(year)
        total_days = calendar.monthrange(year, month)[1]

        working_days = 0
        for day in range(1, total_days + 1):
            try:
                current_date = datetime(year, month, day).date()
                if current_date.weekday() == 6:  # Sunday
                    continue
                if current_date in holidays:     # Holiday
                    continue
                working_days += 1
            except ValueError:
                continue

        self.working_days_cache[cache_key] = working_days
        return working_days

