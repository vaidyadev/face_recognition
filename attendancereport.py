    def calculate_6_month_percentage(self, student):
        total_working_days = 0
        total_present = 0
        
        for m in self.months:
            total_working_days += self.calculate_working_days(m['month'], m['year'])
            present, _, _ = self.get_monthly_attendance(student, m)
            total_present += present

        if total_working_days == 0:
            return 0

        return (total_present / total_working_days) * 100

    def attendance_category_distribution(self):
        distribution = {
            "Excellent (≥90%)": 0,
            "Good (75–90%)": 0,
            "Average (50–75%)": 0,
            "Critical (<50%)": 0
        }

        for student in self.stats:
            # Use cached or efficient calculation
            percentage = self.calculate_6_month_percentage(student)

            if percentage >= 90:
                distribution["Excellent (≥90%)"] += 1
            elif percentage >= 75:
                distribution["Good (75–90%)"] += 1
            elif percentage >= 50:
                distribution["Average (50–75%)"] += 1
            else:
                distribution["Critical (<50%)"] += 1

        return distribution

