    def print_individual_report(self):
    # 🔒 Safety check
        if self.print_individual_btn['state'] == DISABLED:
            return

        # Save dialog
        file = filedialog.asksaveasfilename(
            title="Save Individual Attendance Report",
            defaultextension=".pdf",
            filetypes=[("PDF File", "*.pdf")],
            parent=self.window
        )
        if not file:
            return

        # Selected student
        selection = self.detail_var.get()
        if not selection:
            return

        roll = selection.split(" - ")[0]
        student = next((s for s in self.stats if s['roll'] == roll), None)
        if not student:
            return

        # =========================
        # STUDENT IMAGE (MANDATORY)
        # =========================
        img_path = f"temp_student_{student['id']}.png"
        try:
            pil_img = ImageTk.getimage(self.photo_cache[-1])
            pil_img.save(img_path)
        except:
            messagebox.showerror("Error", "Student image not available.")
            return

        # =========================
        # ATTENDANCE DATA (6 MONTHS)
        # =========================
        months = []
        percentages = []

        for m in reversed(self.months):
            present, _, total_days = self.get_monthly_attendance(student, m)
            pct = (present / total_days * 100) if total_days > 0 else 0
            months.append(m["name"].split()[0])
            percentages.append(pct)

        overall_pct = self.calculate_6_month_percentage(student)

        # =========================
        # GENERATE CHART
        # =========================
        chart_path = f"chart_individual_{student['id']}.png"

        fig, ax = plt.subplots(figsize=(7, 4))
        bars = ax.bar(months, percentages)

        ax.set_ylim(0, 100)
        ax.set_ylabel("Attendance %")
        ax.set_title("Attendance Trend – Last 6 Months")

        # Auto-hide 0 labels
        for bar, pct in zip(bars, percentages):
            if pct > 0:
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    pct + 1,
                    f"{pct:.1f}%",
                    ha="center",
                    fontweight="bold"
                )

        plt.tight_layout()
        fig.savefig(chart_path, dpi=300)
        plt.close(fig)

        # =========================
        # AI INSIGHT
        # =========================
        ai_prompt = f"""
    Student Name: {student['name']}
    Department: {student['dept']}
    6 Month Attendance: {overall_pct:.2f}%
    """

        try:
            completion = ai_client.chat.completions.create(
                model="tngtech/deepseek-r1t2-chimera:free",
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "Write a professional individual attendance insight "
                            "for college administrators. Maximum 40 words. "
                            "No bullet points."
                        )
                    },
                    {"role": "user", "content": ai_prompt}
                ]
            )
            ai_summary = completion.choices[0].message.content.strip()
        except:
            ai_summary = "AI insight unavailable."

        # =========================
        # PDF BUILD
        # =========================
        doc = SimpleDocTemplate(file, pagesize=A4)
        styles = getSampleStyleSheet()
        elements = []

        # Title
        elements.append(Paragraph("INDIVIDUAL ATTENDANCE REPORT", styles["Title"]))
        elements.append(Spacer(1, 20))

        # Student image
        elements.append(RLImage(img_path, width=2*inch, height=2*inch))
        elements.append(Spacer(1, 15))

        # Student info table
        info_table = Table([
            ["Name", student["name"]],
            ["Roll No", student["roll"]],
            ["Department", student["dept"]],
            ["Attendance (6 Months)", f"{overall_pct:.2f}%"]
        ], colWidths=[2.5*inch, 3.5*inch])

        info_table.setStyle(TableStyle([
            ("GRID", (0,0), (-1,-1), 1, colors.black),
            ("BACKGROUND", (0,0), (0,-1), colors.lightgrey),
            ("FONTNAME", (0,0), (0,-1), "Helvetica-Bold")
        ]))

        elements.append(info_table)
        elements.append(PageBreak())

        # Chart
        elements.append(Paragraph("Attendance Trend", styles["Heading2"]))
        elements.append(Spacer(1, 10))
        elements.append(RLImage(chart_path, width=6*inch, height=4*inch))
        elements.append(Spacer(1, 20))

        # AI Insight
        elements.append(Paragraph("AI Attendance Insight", styles["Heading2"]))
        elements.append(Paragraph(ai_summary, styles["Normal"]))

        # Build PDF with SAME branding
        doc.build(
            elements,
            onFirstPage=self.draw_branding,
            onLaterPages=self.draw_branding
        )

        # =========================
        # CLEANUP
        # =========================
        for f in [img_path, chart_path]:
            if os.path.exists(f):
                os.remove(f)

        messagebox.showinfo("Success", "Individual report printed successfully!",parent=self.window)

