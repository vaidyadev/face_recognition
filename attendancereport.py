    def calculate_statistics(self):
        """Process raw data into usable statistics"""
        # We can now use the pre-processed attendance_map for faster counting
        # But for initial setup, iterating once is fine.
        
        # Re-using the logic but ensuring we handle duplicates correctly
        attendance_summary = defaultdict(lambda: {'present': 0, 'absent': 0, 'total': 0, 'dates': []})
        
        # Fast lookup meta info
        meta_info = {}
        
        for row in self.mydata:
            if len(row) >= 7:
                student_id = row[0]
                
                # Store meta info only once per student
                if student_id not in meta_info:
                    meta_info[student_id] = {
                        'name': row[1],
                        'roll': row[2],
                        'dept': row[3],
                        'time': row[4]
                    }
                
                date_str = row[5]
                status = row[6].strip().lower()
                
                attendance_summary[student_id]['total'] += 1
                attendance_summary[student_id]['dates'].append(date_str)
                
                if status == 'present':
                    attendance_summary[student_id]['present'] += 1
                else:
                    attendance_summary[student_id]['absent'] += 1
        
        stats_list = []
        for s_id, data in attendance_summary.items():
            meta = meta_info.get(s_id)
            if meta:
                percentage = (data['present'] / data['total'] * 100) if data['total'] > 0 else 0
                stats_list.append({
                    'id': s_id,
                    'name': meta['name'],
                    'roll': meta['roll'],
                    'dept': meta['dept'],
                    'time': meta['time'],
                    'present': data['present'],
                    'absent': data['absent'],
                    'total': data['total'],
                    'percentage': percentage,
                    'dates': data['dates'] # Keeps list of dates for specific iterating
                })
        
        return sorted(stats_list, key=lambda x: x['percentage'], reverse=True)

    def get_monthly_attendance(self, student, month_data):
        """
        OPTIMIZATION: Calculate attendance for a specific month using O(1) lookup map.
        """
        month = month_data['month']
        year = month_data['year']
        
        present_days = 0
        total_recorded_days = 0
        
        # We only need to check dates associated with this student
        # Optimize: Filter dates by string parsing is slow, but assuming format DD/MM/YYYY
        # checking the suffix is faster than strptime if date format is strictly consistent.
        # Fallback to strptime for safety.
        
        target_suffix = f"/{month:02d}/{year}" # e.g. /05/2024
        
        # Get the map for this student
        student_att_map = self.attendance_map.get(student['id'], {})
        
        # Iterate only dates this student has records for
        for date_str in student['dates']:
            # Fast string check first
            if date_str.endswith(target_suffix) or f"/{month}/" in date_str:
                try:
                    # Verify exact match
                    d_obj = datetime.strptime(date_str, "%d/%m/%Y")
                    if d_obj.month == month and d_obj.year == year:
                        total_recorded_days += 1
                        # O(1) Lookup instead of iterating mydata
                        status = student_att_map.get(date_str, "").lower()
                        if status == 'present':
                            present_days += 1
                except ValueError:
                    continue

        working_days = self.calculate_working_days(month, year)
        return present_days, total_recorded_days, working_days

