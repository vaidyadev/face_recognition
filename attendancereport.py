            conn = mysql.connector.connect(host='localhost', port=3307, 
                                          username='root', password='1582', 
                                          database='face_recognizer')
            cursor = conn.cursor()
            cursor.execute("SELECT * FROM student WHERE Roll=%s", (roll,))
